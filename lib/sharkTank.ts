function inr(rupees: number) {
  if (rupees >= 1e7) {
    const cr = rupees / 1e7;
    return `₹${cr >= 100 ? Math.round(cr) : Number(cr.toFixed(2))} crore`;
  }
  return `₹${Math.round(rupees / 1e5)} lakh`;
}

function toCase(p: Pitch): CaseStudy {
  const amount = p.amountLakh * 1e5;
  const valuation = amount / (p.equityPct / 100);
  const season = SHARK_TANK_SEASONS.find((s) => s.season === p.season)!;
  const deal = `${inr(amount)} for ${p.equityPct}% equity${p.extra ? `, ${p.extra}` : ""}`;
  const structure = p.extra
    ? /royalty/.test(p.extra)
      ? " The royalty means investors receive a share of revenue until a set amount is returned, which lowers their risk and lets founders give away less equity."
      : /debt/.test(p.extra)
        ? " Part of the money came as debt, which must be repaid with interest but doesn't dilute the founders' ownership."
        : ""
    : "";

  return {
    slug: `shark-tank-india-${p.slug}`,
    title: `${p.brand} Shark Tank India: deal, valuation & business model`,
    collection: "shark-tank-india",
    company: p.brand,
    country: "India",
    region: "India",
    period: `Shark Tank India Season ${p.season}`,
    kind: "build",
    industrySlug: p.industrySlug,
    summary: p.summary,
    story: [
      ...p.story,
      `On Shark Tank India Season ${p.season}, ${p.brand} closed a deal of ${deal}. The equity portion implies a valuation of about ${inr(valuation)} for the business.${structure}`,
    ],
    keyNumbers: [
      { label: "Deal", value: deal },
      { label: "Implied valuation (equity portion)", value: `about ${inr(valuation)}` },
      { label: "Season", value: `${p.season} (aired ${season.aired})` },
      ...(p.city ? [{ label: "Based in", value: p.city }] : []),
      { label: "What they sell", value: p.product },
    ],
    timeline: [
      { year: season.year, event: `Pitched on Shark Tank India Season ${p.season}.` },
      { year: "Deal", event: deal.charAt(0).toUpperCase() + deal.slice(1) + "." },
    ],
    lesson: p.lesson,
    takeaways: p.takeaways,
    lawSlugs: p.lawSlugs,
  };
}

export const SHARK_TANK_CASES: CaseStudy[] = PITCHES.map(toCase);
